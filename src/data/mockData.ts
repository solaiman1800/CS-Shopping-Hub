export const toBengaliNumber = (num: number | string): string => {
  const bnDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  const str = num.toLocaleString('en-US');
  return str.replace(/[0-9]/g, (w) => bnDigits[+w]);
};

export const formatPrice = (amount: number, isBn: boolean = true): string => {
  if (!isBn) return `৳ ${amount.toLocaleString()}`;
  return `৳${toBengaliNumber(amount)}`;
};

